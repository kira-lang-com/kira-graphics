void kira_wayland_resize_frame_destroy(void *surface) {
    struct kira_wayland_resize_frame **link = &kira_wayland_resize_frames;
    while (*link && (*link)->root != surface) link = &(*link)->next;
    if (!*link) return;
    struct kira_wayland_resize_frame *frame = *link;
    *link = frame->next;
    for (int i = 0; i < KIRA_WAYLAND_RESIZE_ZONE_COUNT; ++i) {
        if (frame->viewports[i]) wp_viewport_destroy(frame->viewports[i]);
        if (frame->subsurfaces[i]) wl_subsurface_destroy(frame->subsurfaces[i]);
        if (frame->zones[i]) wl_surface_destroy(frame->zones[i]);
    }
    if (frame->buffer) wl_buffer_destroy(frame->buffer);
    if (frame->pool) wl_shm_pool_destroy(frame->pool);
    free(frame);
}

