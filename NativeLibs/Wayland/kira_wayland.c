int32_t kira_wayland_display_pump(void *display) {
    struct wl_display *wl_display = display;

    // prepare_read refuses while decoded events are still queued. Drain those
    // first, then reserve the socket read so no event can race between the
    // pending check and poll.
    while (wl_display_prepare_read(wl_display) != 0) {
        if (wl_display_dispatch_pending(wl_display) < 0) return -1;
    }

    // Requests generated by the last frame must reach the compositor before
    // checking for its replies. EAGAIN is harmless for a nonblocking pump; the
    // next frame retries it.
    wl_display_flush(wl_display);

    struct pollfd source = {
        .fd = wl_display_get_fd(wl_display),
        .events = POLLIN,
        .revents = 0,
    };
    int ready = poll(&source, 1, 0);
    if (ready > 0 && (source.revents & POLLIN)) {
        if (wl_display_read_events(wl_display) < 0) return -1;
        return wl_display_dispatch_pending(wl_display);
    }

    wl_display_cancel_read(wl_display);
    return ready < 0 ? -1 : 0;
}

