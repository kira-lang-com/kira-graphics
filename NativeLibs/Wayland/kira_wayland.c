enum { KIRA_WAYLAND_RESIZE_MARGIN = 7, KIRA_WAYLAND_RESIZE_ZONE_COUNT = 8 };

struct kira_wayland_resize_globals {
    struct wl_subcompositor *subcompositor;
    struct wl_shm *shm;
    struct wp_viewporter *viewporter;
};

struct kira_wayland_resize_frame {
    struct wl_surface *root;
    struct xdg_surface *xdg_surface;
    struct wl_buffer *buffer;
    struct wl_shm_pool *pool;
    struct wl_surface *zones[KIRA_WAYLAND_RESIZE_ZONE_COUNT];
    struct wl_subsurface *subsurfaces[KIRA_WAYLAND_RESIZE_ZONE_COUNT];
    struct wp_viewport *viewports[KIRA_WAYLAND_RESIZE_ZONE_COUNT];
    uint32_t edges[KIRA_WAYLAND_RESIZE_ZONE_COUNT];
    int32_t offsets_x[KIRA_WAYLAND_RESIZE_ZONE_COUNT];
    int32_t offsets_y[KIRA_WAYLAND_RESIZE_ZONE_COUNT];
    struct kira_wayland_resize_frame *next;
};

static struct kira_wayland_resize_frame *kira_wayland_resize_frames;

static void kira_wayland_resize_global(
    void *data, struct wl_registry *registry, uint32_t name,
    const char *interface, uint32_t version
) {
    struct kira_wayland_resize_globals *globals = data;
    if (strcmp(interface, "wl_subcompositor") == 0) {
        globals->subcompositor = wl_registry_bind(registry, name, &wl_subcompositor_interface, 1);
    } else if (strcmp(interface, "wl_shm") == 0) {
        globals->shm = wl_registry_bind(registry, name, &wl_shm_interface, version > 1 ? 1 : version);
    } else if (strcmp(interface, "wp_viewporter") == 0) {
        globals->viewporter = wl_registry_bind(registry, name, &wp_viewporter_interface, 1);
    }
}

static void kira_wayland_resize_global_remove(void *data, struct wl_registry *registry, uint32_t name) {
    (void)data; (void)registry; (void)name;
}

static struct kira_wayland_resize_frame *kira_wayland_resize_frame_find(void *surface) {
    struct kira_wayland_resize_frame *frame = kira_wayland_resize_frames;
    while (frame && frame->root != surface) frame = frame->next;
    return frame;
}

static void kira_wayland_resize_zone_geometry(
    struct kira_wayland_resize_frame *frame, int index,
    int32_t x, int32_t y, int32_t width, int32_t height
) {
    if (width < 1) width = 1;
    if (height < 1) height = 1;
    frame->offsets_x[index] = x;
    frame->offsets_y[index] = y;
    wl_subsurface_set_position(frame->subsurfaces[index], x, y);
    wp_viewport_set_destination(frame->viewports[index], width, height);
    wl_surface_attach(frame->zones[index], frame->buffer, 0, 0);
    wl_surface_damage(frame->zones[index], 0, 0, width, height);
    wl_surface_commit(frame->zones[index]);
}

void kira_wayland_resize_frame_update(void *surface, int32_t width, int32_t height) {
    struct kira_wayland_resize_frame *frame = kira_wayland_resize_frame_find(surface);
    if (!frame || width < 1 || height < 1) return;
    // The compositor's placement/shadow bounds are the visible content, never
    // the transparent input subsurfaces surrounding it. This is pending surface
    // state and must follow every configured size, not just the initial one.
    xdg_surface_set_window_geometry(frame->xdg_surface, 0, 0, width, height);
    const int32_t m = KIRA_WAYLAND_RESIZE_MARGIN;
    kira_wayland_resize_zone_geometry(frame, 0, 0, -m, width, m);
    kira_wayland_resize_zone_geometry(frame, 1, 0, height, width, m);
    kira_wayland_resize_zone_geometry(frame, 2, -m, 0, m, height);
    kira_wayland_resize_zone_geometry(frame, 3, width, 0, m, height);
    kira_wayland_resize_zone_geometry(frame, 4, -m, -m, m, m);
    kira_wayland_resize_zone_geometry(frame, 5, width, -m, m, m);
    kira_wayland_resize_zone_geometry(frame, 6, -m, height, m, m);
    kira_wayland_resize_zone_geometry(frame, 7, width, height, m, m);
}

int32_t kira_wayland_resize_frame_create(
    void *display, void *surface, void *compositor, void *xdg_surface,
    int32_t width, int32_t height
) {
    struct wl_registry *registry = wl_display_get_registry(display);
    if (!registry) return 0;
    struct kira_wayland_resize_globals globals = {0};
    const struct wl_registry_listener listener = {
        .global = kira_wayland_resize_global,
        .global_remove = kira_wayland_resize_global_remove,
    };
    wl_registry_add_listener(registry, &listener, &globals);
    int ok = wl_display_roundtrip(display) >= 0;
    wl_registry_destroy(registry);
    if (!ok || !globals.subcompositor || !globals.shm || !globals.viewporter) return 0;

    int fd = memfd_create("kira-wayland-resize", MFD_CLOEXEC);
    if (fd < 0 || ftruncate(fd, 4) != 0) { if (fd >= 0) close(fd); return 0; }
    uint32_t *pixel = mmap(NULL, 4, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
    if (pixel == MAP_FAILED) { close(fd); return 0; }
    *pixel = 0;

    struct kira_wayland_resize_frame *frame = calloc(1, sizeof(*frame));
    if (!frame) { munmap(pixel, 4); close(fd); return 0; }
    frame->root = surface;
    frame->xdg_surface = xdg_surface;
    frame->pool = wl_shm_create_pool(globals.shm, fd, 4);
    frame->buffer = wl_shm_pool_create_buffer(frame->pool, 0, 1, 1, 4, WL_SHM_FORMAT_ARGB8888);
    munmap(pixel, 4);
    close(fd);
    if (!frame->pool || !frame->buffer) { free(frame); return 0; }

    const uint32_t edges[KIRA_WAYLAND_RESIZE_ZONE_COUNT] = {
        XDG_TOPLEVEL_RESIZE_EDGE_TOP, XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM,
        XDG_TOPLEVEL_RESIZE_EDGE_LEFT, XDG_TOPLEVEL_RESIZE_EDGE_RIGHT,
        XDG_TOPLEVEL_RESIZE_EDGE_TOP_LEFT, XDG_TOPLEVEL_RESIZE_EDGE_TOP_RIGHT,
        XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM_LEFT, XDG_TOPLEVEL_RESIZE_EDGE_BOTTOM_RIGHT,
    };
    for (int i = 0; i < KIRA_WAYLAND_RESIZE_ZONE_COUNT; ++i) {
        frame->edges[i] = edges[i];
        frame->zones[i] = wl_compositor_create_surface(compositor);
        frame->subsurfaces[i] = wl_subcompositor_get_subsurface(
            globals.subcompositor, frame->zones[i], surface
        );
        frame->viewports[i] = wp_viewporter_get_viewport(globals.viewporter, frame->zones[i]);
        if (!frame->zones[i] || !frame->subsurfaces[i] || !frame->viewports[i]) return 0;
    }
    frame->next = kira_wayland_resize_frames;
    kira_wayland_resize_frames = frame;
    kira_wayland_resize_frame_update(surface, width, height);
    wp_viewporter_destroy(globals.viewporter);
    wl_shm_destroy(globals.shm);
    wl_subcompositor_destroy(globals.subcompositor);
    return 1;
}

uint32_t kira_wayland_resize_frame_edge(void *surface, void *event_surface) {
    struct kira_wayland_resize_frame *frame = kira_wayland_resize_frame_find(surface);
    if (!frame) return 0;
    for (int i = 0; i < KIRA_WAYLAND_RESIZE_ZONE_COUNT; ++i)
        if (frame->zones[i] == event_surface) return frame->edges[i];
    return 0;
}

