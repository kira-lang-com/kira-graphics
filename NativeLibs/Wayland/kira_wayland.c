struct kira_wayland_cursor_shape_bind {
    void *manager;
};

static void kira_wayland_cursor_shape_global(
    void *data,
    struct wl_registry *registry,
    uint32_t name,
    const char *interface,
    uint32_t version
) {
    struct kira_wayland_cursor_shape_bind *bind = data;
    if (bind->manager || strcmp(interface, "wp_cursor_shape_manager_v1") != 0) return;
    uint32_t bind_version = version > 1 ? 1 : version;
    bind->manager = wl_registry_bind(
        registry,
        name,
        &wp_cursor_shape_manager_v1_interface,
        bind_version
    );
}

static void kira_wayland_cursor_shape_global_remove(
    void *data,
    struct wl_registry *registry,
    uint32_t name
) {
    (void)data;
    (void)registry;
    (void)name;
}

void *kira_wayland_display_bind_cursor_shape_manager(void *display) {
    struct wl_registry *registry = wl_display_get_registry(display);
    if (!registry) return NULL;
    struct kira_wayland_cursor_shape_bind bind = {0};
    const struct wl_registry_listener listener = {
        .global = kira_wayland_cursor_shape_global,
        .global_remove = kira_wayland_cursor_shape_global_remove,
    };
    wl_registry_add_listener(registry, &listener, &bind);
    if (wl_display_roundtrip(display) < 0) bind.manager = NULL;
    wl_registry_destroy(registry);
    return bind.manager;
}

